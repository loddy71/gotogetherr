/**
 * Generates src/lib/data/land-dots.ts: a grid of points that fall on land,
 * used to draw the dotted world map. Source: Natural Earth 1:110m land via
 * the world-atlas package (public domain).
 *
 *   node scripts/gen-land-dots.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { geoContains } from 'd3-geo';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/land-110m.json'), 'utf8'));
const land = feature(topo, topo.objects.land);

const STEP = 2;
const LAT_MIN = -56;
const LAT_MAX = 76;

const points = [];
for (let lat = LAT_MAX; lat >= LAT_MIN; lat -= STEP) {
  for (let lon = -180 + STEP / 2; lon < 180; lon += STEP) {
    if (geoContains(land, [lon, lat])) points.push(Math.round(lon * 10) / 10, lat);
  }
}

const body = `/**
 * Land points on a ${STEP}° grid (lon, lat pairs, flattened) between
 * ${LAT_MIN}° and ${LAT_MAX}° latitude. Generated by scripts/gen-land-dots.mjs
 * from Natural Earth 1:110m land (public domain) — do not edit by hand.
 */
export const LAND_STEP = ${STEP};
export const LAT_RANGE = [${LAT_MIN}, ${LAT_MAX}] as const;
export const LAND_DOTS: readonly number[] = [${points.join(',')}];
`;
writeFileSync(new URL('../src/lib/data/land-dots.ts', import.meta.url), body);
console.log(`${points.length / 2} land dots written`);
