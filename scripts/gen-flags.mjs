/**
 * Writes src/lib/data/flags.ts: SVG flags (country-flag-icons, MIT) for just
 * the countries in the city list, keyed by ISO 3166-1 alpha-2. Emoji flags
 * render as letter pairs on Windows, so the app draws these instead.
 *
 *   node scripts/gen-flags.mjs
 *
 * Re-run after adding a city in a new country.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const pkg = dirname(require.resolve('country-flag-icons/package.json'));
const cities = readFileSync(new URL('../src/lib/data/cities.ts', import.meta.url), 'utf8');
const isos = new Set();
for (const m of cities.matchAll(/flag: '([^']+)'/g)) {
  const iso = [...m[1]].map((ch) => String.fromCharCode(ch.codePointAt(0) - 0x1f1e6 + 65)).join('');
  isos.add(iso);
}
const entries = [...isos].sort().map((iso) => {
  const file = join(pkg, 'string', '3x2', `${iso}.js`);
  const svg = readFileSync(file, 'utf8').match(/export default '(.*)'/s)[1];
  return `  ${iso}: '${svg.replace(/'/g, "\\'")}',`;
});
writeFileSync(
  new URL('../src/lib/data/flags.ts', import.meta.url),
  `/**
 * 3:2 SVG flags for the countries in the city list, keyed by ISO 3166-1
 * alpha-2. Generated by scripts/gen-flags.mjs from country-flag-icons (MIT);
 * do not edit by hand.
 */
export const FLAG_SVGS: Record<string, string> = {
${entries.join('\n')}
};
`,
);
console.log(`${isos.size} flags`);
